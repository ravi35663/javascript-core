/*
==> Blocking:
    ->  Blocking is a process where execution of the additional code in node js must wait until non-js 
        operations complete their tasks .
    ->  
*/
/*
==> Asynchronous : -
    —>  When request is made to the server instead of waiting for response to complete, server continues to 
        process other requests. That is known as asynchronous. Processes cannot wait to complete the other 
        processes .
    —>  When response is completed the response sent back to caller object using “rollback mechanism”
*/

/*
==> Multi-threading Model : - 
    —> Multiple request and response. 
    —> Each request is handled by separate thread.
*/